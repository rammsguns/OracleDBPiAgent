import { expect, it } from 'vitest';
import { classifySql } from '../../src/oracle/sqlPolicy.js';
it.each([
	"SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(:id, :child, 'TYPICAL'))",
	"SELECT PLAN_TABLE_OUTPUT FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR('abc', 0, 'TYPICAL'));",
	"SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'TYPICAL'))",
])('allows exact display form %s', sql => expect(() => classifySql(sql)).not.toThrow());
it.each([
	"SELECT DBMS_XPLAN.DISPLAY_CURSOR(:id,0,'TYPICAL') FROM dual",
	"SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(LOWER(:id),0,'TYPICAL'))",
	"SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR((SELECT x FROM t),0,'TYPICAL'))",
	"SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(:id,DBMS_LOCK.SLEEP(1),'TYPICAL'))",
	"SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(:id,0,'TYPICAL')) UNION SELECT * FROM t",
	"SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(:id,0,'TYPICAL')); DELETE FROM t",
	"SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(:id,0,'TYPICAL')) WHERE DBMS_PIPE.RECEIVE_MESSAGE('x')=1",
	"SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY(:id,0,'TYPICAL'))",
	"SELECT * FROM TABLE(DBMS_SQL.EXECUTE(:id))",
	"SELECT * FROM TABLE(SYS.DBMS_XPLAN.DISPLAY_CURSOR(:id,0,'TYPICAL'))",
	'SELECT * FROM TABLE("DBMS_XPLAN"."DISPLAY_CURSOR"(:id,0,\'TYPICAL\'))',
	"BEGIN DBMS_XPLAN.DISPLAY_CURSOR(:id,0,'TYPICAL'); END;",
])('rejects broader package form %s', sql => expect(() => classifySql(sql)).toThrow());
